#!/usr/bin/env python3
"""gen_history_index.py — THE INDEX AT THE HEAD OF EVERY HISTORY FILE (GitHub #282 item E, 14z-201).

Every archive (`*_HISTORY.md` at the root, every `*_history.md` or `*_HISTORY.md` under docs/) opens with a GENERATED index: one line
per entry, `- L<line> <entry heading>`, the line number being the entry's line in the file as written, so a reader
opens the entry directly (`Read offset=<line>`) instead of reading or grepping a file of thousands of lines. The
maintainer's ask (#282): "_HISTORY FILES should beging with an index to immediately be able to access a section".

THE BLOCK. The index sits between two marker lines, after the file's first line (its `# ` title) and one blank line:

    <!-- HISTORY INDEX: generated by tools/gen_history_index.py from this file's entry headings; do not edit -->
    ...one `- L<n> <heading>` line per entry, in file order...
    <!-- /HISTORY INDEX -->

The block is the only thing this tool writes: the archived entries themselves are never touched (CLAUDE.md
[VSP-17]: archived entries are never rewritten). The line numbers count the block itself, so they are exact in the
file as written; every edit above an entry moves them, which is why the index is regenerated in the commit that
changes the file and `tests/test_history_index.sh` fails on a stale one.

WHAT AN ENTRY IS, per file (ENTRY below): the heading form that file's entries actually use — measured at 14z-201,
not assumed (STATE_HISTORY's records are `## Session …`; NEXT_SESSION_HISTORY's archived openers are blockquoted
`> # NEXT SESSION …` lines). Fenced code is skipped. A heading is cut to 140 characters.

  gen_history_index.py [--root DIR]            rewrite every configured file's block
  gen_history_index.py [--root DIR] --check    exit 1 if any block differs from a regeneration, or if an archive
                                               exists that ENTRY does not configure (names each)
"""
import argparse
import glob
import os
import re
import sys

ENTRY = {
    "DECISIONS_HISTORY.md": r"^## ",
    "HANDOFF_HISTORY.md": r"^#{1,2} ",
    "STATE_HISTORY.md": r"^(# |## Sessions? )",
    "docs/GOTCHAS_history.md": r"^#{1,3} ",
    "docs/NEXT_SESSION_HISTORY.md": r"^(> )?# NEXT SESSION|^## Archived opener",
    "docs/game/engine_internals_history.md": r"^## ",
    "docs/platform/mister_history.md": r"^## ",
    "docs/project/build_dir_triage_history.md": r"^#{1,2} ",
    "docs/project/cps2_wide_history.md": r"^#{2,3} ",
    "docs/project/harness_hardening_history.md": r"^## ",
    "docs/project/tables/reconciliation_history.md": r"^## ",
    "docs/project/tenant_manifest_history.md": r"^## ",
}
BEGIN = "<!-- HISTORY INDEX: generated by tools/gen_history_index.py from this file's entry headings; do not edit -->"
END = "<!-- /HISTORY INDEX -->"
CUT = 140


def archives(root):
    found = set(os.path.relpath(p, root) for p in glob.glob(os.path.join(root, "*_HISTORY.md")))
    for pat in ("*_history.md", "*_HISTORY.md"):
        found |= set(os.path.relpath(p, root) for p in glob.glob(os.path.join(root, "docs", "**", pat), recursive=True))
    return sorted(found)


def strip_block(lines):
    """the file's lines without an existing index block (and the one blank line after it)"""
    if BEGIN not in lines:
        return lines
    b = lines.index(BEGIN)
    e = lines.index(END, b)
    rest = lines[e + 1:]
    if rest and rest[0] == "":
        rest = rest[1:]
    return lines[:b] + rest


def render(text, pattern):
    body = strip_block(text.split("\n"))
    # the output is: the title, one blank line, the block (BEGIN, one line per entry, END, one blank line), the rest
    head = body[:1] + [""]
    rest = body[1:]
    if rest and rest[0] == "":
        rest = rest[1:]
    rx, fence, found = re.compile(pattern), False, []
    for k, ln in enumerate(rest):
        if ln.lstrip("> ").startswith("```"):
            fence = not fence
            continue
        if not fence and rx.match(ln):
            found.append((k, ln.strip()[:CUT]))
    before = len(head) + 1 + len(found) + 2          # head, BEGIN, the entries, END, the blank line
    block = [BEGIN] + [f"- L{before + k + 1} {h}" for k, h in found] + [END, ""]
    return "\n".join(head + block + rest)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = 0
    for p in archives(a.root):
        if p not in ENTRY:
            print(f"UNCONFIGURED archive {p}: give it an ENTRY pattern in tools/gen_history_index.py")
            bad = 1
    for p, pat in ENTRY.items():
        f = os.path.join(a.root, p)
        if not os.path.exists(f):
            print(f"MISSING configured archive {p}")
            bad = 1
            continue
        text = open(f, encoding="utf-8").read()
        new = render(text, pat)
        if a.check:
            if new != text:
                print(f"STALE index in {p} (regenerate: python3 tools/gen_history_index.py)")
                old_idx = set(l for l in text.split("\n") if l.startswith("- L"))
                for l in [l for l in new.split("\n") if l.startswith("- L") and l not in old_idx][:5]:
                    print(f"    expected {l}")
                bad = 1
        elif new != text:
            open(f, "w", encoding="utf-8").write(new)
            print(f"wrote {p}")
    # self-check: every index line names the line its heading is on
    for p in ENTRY:
        f = os.path.join(a.root, p)
        if not os.path.exists(f) or a.check and bad:
            continue
        lines = open(f, encoding="utf-8").read().split("\n")
        if BEGIN not in lines:
            continue
        b, e = lines.index(BEGIN), lines.index(END)
        for l in lines[b + 1:e]:
            m = re.match(r"- L(\d+) (.*)", l)
            if not m or lines[int(m.group(1)) - 1].strip()[:CUT] != m.group(2):
                print(f"WRONG LINE in {p}: {l[:120]}")
                bad = 1
                break
    if a.check and not bad:
        print(f"history indexes current: {len(ENTRY)} archives")
    sys.exit(bad)


if __name__ == "__main__":
    main()
